import 'package:easy_localization/easy_localization.dart';

/// Χειρισμός της ετικέτας τοποθεσίας μιας αγγελίας (`locationLabel`).
///
/// ΑΡΧΗ: στη βάση αποθηκεύεται ΜΟΝΟ πραγματικό όνομα τόπου («Κασσώπης,
/// Πρέβεζα») ή ΚΕΝΟ. Ποτέ κείμενο εμφάνισης.
///
/// Παλιότερα, όταν αποτύγχανε το reverse geocoding, αποθηκευόταν hardcoded
/// ΕΛΛΗΝΙΚΟ κείμενο («Επιλεγμένη τοποθεσία»). Αυτό είχε δύο προβλήματα:
///  1. Άγγλοι/Ισπανοί χρήστες έβλεπαν ελληνικά μέσα στο δικό τους UI.
///  2. Μολύνει την αναζήτηση: το `locationLabel` μπαίνει στα searchKeywords,
///     οπότε η λέξη «τοποθεσία» θα ταίριαζε με δεκάδες άσχετες αγγελίες.
///
/// Η μετάφραση γίνεται πλέον ΣΤΗΝ ΕΜΦΑΝΙΣΗ, μέσω [display].
class PlaceLabel {
  PlaceLabel._();

  /// Ετικέτες που ΔΕΝ είναι πραγματικοί τόποι.
  ///
  /// Περιλαμβάνει τα ελληνικά sentinels που έγραφαν οι ΠΑΛΙΕΣ εκδόσεις — οι
  /// αγγελίες τους υπάρχουν ακόμα στη βάση και πρέπει να αναγνωρίζονται.
  /// ΜΗΝ τα αφαιρέσεις: θα εμφανίζονταν ξανά ως «τόπος».
  static const placeholders = {
    'Τρέχουσα τοποθεσία',
    'Επιλεγμένη τοποθεσία',
    'Δεν βρέθηκε τοποθεσία',
    '',
  };

  /// True αν η ετικέτα δεν αντιστοιχεί σε πραγματικό τόπο.
  static bool isPlaceholder(String? label) =>
      placeholders.contains((label ?? '').trim());

  /// Το κείμενο που βλέπει ο χρήστης — μεταφρασμένο όταν δεν υπάρχει τόπος.
  static String display(String? label) =>
      isPlaceholder(label) ? 'cl.locationSelected'.tr() : label!.trim();

  /// Ό,τι πρέπει να ΑΠΟΘΗΚΕΥΤΕΙ: πραγματικός τόπος ή κενό.
  static String toStore(String? label) =>
      isPlaceholder(label) ? '' : label!.trim();
}
